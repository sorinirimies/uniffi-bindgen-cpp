//! The public C++ header of a component.

use std::collections::BTreeSet;
use std::fmt::Write;

use uniffi_bindgen::interface::{
    AsType, Callable, CallbackInterface, DefaultValue, Enum, Literal, Object, Record, Type,
};

use super::names::{class, doc, field, member, var};
use super::types::Gen;
use super::values::{ValueKind, trait_declarations};

/// A codec specialization: the class, and its member definitions, which have to come
/// after every codec is declared.
struct Codec {
    declaration: String,
    definition: String,
}

/// A value type that has to be defined before others can use it.
enum ValueDef<'a> {
    Record(&'a Record),
    Enum(&'a Enum),
}

impl ValueDef<'_> {
    fn name(&self) -> &str {
        match self {
            ValueDef::Record(r) => r.name(),
            ValueDef::Enum(e) => e.name(),
        }
    }
}

impl Gen<'_> {
    /// Record and enum definitions ordered so that every type comes after the ones it contains.
    fn ordered_value_defs(&self) -> Vec<ValueDef<'_>> {
        let mut all: Vec<ValueDef<'_>> = Vec::new();
        all.extend(self.ci.enum_definitions().iter().map(ValueDef::Enum));
        all.extend(self.ci.record_definitions().iter().map(ValueDef::Record));
        let mut done: BTreeSet<String> = BTreeSet::new();
        let mut out: Vec<ValueDef<'_>> = Vec::new();
        let names: BTreeSet<String> = all.iter().map(|d| d.name().to_owned()).collect();
        for def in &all {
            self.visit_def(def, &all, &names, &mut done, &mut out);
        }
        out
    }

    fn visit_def<'a>(
        &self,
        def: &ValueDef<'a>,
        all: &[ValueDef<'a>],
        names: &BTreeSet<String>,
        done: &mut BTreeSet<String>,
        out: &mut Vec<ValueDef<'a>>,
    ) {
        if !done.insert(def.name().to_owned()) {
            return;
        }
        let fields: Vec<Type> = match def {
            ValueDef::Record(r) => r.fields().iter().map(|f| f.as_type()).collect(),
            ValueDef::Enum(e) => e
                .variants()
                .iter()
                .flat_map(|v| v.fields().iter().map(|f| f.as_type()))
                .collect(),
        };
        let mut deps = Vec::new();
        for ty in &fields {
            self.complete_type_deps(ty, &mut deps);
        }
        for name in deps {
            if names.contains(name)
                && let Some(dep) = all.iter().find(|d| d.name() == name)
            {
                self.visit_def(dep, all, names, done, out);
            }
        }
        out.push(match def {
            ValueDef::Record(r) => ValueDef::Record(r),
            ValueDef::Enum(e) => ValueDef::Enum(e),
        });
    }

    /// The records and enums a member of type `ty` needs complete. `std::vector` and
    /// `std::shared_ptr` accept incomplete types, so what they hold can come later;
    /// that is what lets a type refer back to itself through a sequence.
    fn complete_type_deps<'t>(&self, ty: &'t Type, deps: &mut Vec<&'t str>) {
        match ty {
            Type::Enum { name, .. } if self.is_error_enum(name) => {}
            Type::Record { name, .. } | Type::Enum { name, .. } => deps.push(name),
            Type::Optional { inner_type } => self.complete_type_deps(inner_type, deps),
            Type::Map {
                key_type,
                value_type,
            } => {
                self.complete_type_deps(key_type, deps);
                self.complete_type_deps(value_type, deps);
            }
            Type::Custom { builtin, .. } => self.complete_type_deps(builtin, deps),
            _ => {}
        }
    }

    /// The namespaces of other components this one refers to.
    pub(crate) fn external_namespaces(&self) -> BTreeSet<String> {
        self.ci
            .iter_external_types()
            .filter_map(|t| self.ci.namespace_for_type(t).ok().map(str::to_owned))
            .collect()
    }

    pub(crate) fn emit_header(&self) -> String {
        let mut out = String::new();
        let ns = &self.ns;
        let _ = writeln!(
            out,
            "// This file was autogenerated by uniffi-bindgen-cpp. Do not edit it by hand.\n"
        );
        let _ = writeln!(out, "#pragma once\n\n#include \"uniffi_runtime.hpp\"");
        for ext in self.external_namespaces() {
            let _ = writeln!(out, "#include \"{ext}.hpp\"");
        }
        for custom in self.config.custom_types.values() {
            for include in &custom.includes {
                let _ = writeln!(out, "#include {include}");
            }
        }
        out.push('\n');
        out.push_str(&doc(self.ci.namespace_docstring(), 0));
        let _ = writeln!(out, "namespace {ns} {{\n");

        out.push_str(&self.emit_forward_declarations());
        out.push_str(&self.emit_custom_aliases());

        for def in self.ordered_value_defs() {
            match def {
                ValueDef::Enum(e) if self.is_error_enum(e.name()) => {
                    out.push_str(&self.emit_error_class(e));
                }
                ValueDef::Enum(e) if e.is_flat() => out.push_str(&self.emit_flat_enum(e)),
                ValueDef::Enum(e) => out.push_str(&self.emit_data_enum(e)),
                ValueDef::Record(r) => out.push_str(&self.emit_record(r)),
            }
        }

        for cb in self.ci.callback_interface_definitions() {
            out.push_str(&self.emit_callback_interface_class(cb));
        }
        for obj in self.ci.object_definitions() {
            out.push_str(&self.emit_object_class(obj));
        }
        for func in self.ci.function_definitions() {
            out.push_str(&doc(func.docstring(), 0));
            let _ = writeln!(out, "{};\n", self.signature(func, &var(func.name()), true));
        }

        out.push_str(&self.value_inline_definitions());
        out.push_str(&self.emit_detail_declarations());
        let _ = writeln!(out, "}}  // namespace {ns}\n");
        out.push_str(&self.emit_codecs());
        out.push_str(&self.value_std_hash());
        out
    }

    fn emit_forward_declarations(&self) -> String {
        let mut out = String::new();
        for e in self.ci.enum_definitions() {
            if self.is_error_enum(e.name()) {
                let _ = writeln!(out, "class {};", class(e.name()));
            } else if e.is_flat() {
                // Flat enums are defined in full, in dependency order.
            } else {
                let _ = writeln!(out, "struct {};", class(e.name()));
            }
        }
        for r in self.ci.record_definitions() {
            let _ = writeln!(out, "struct {};", class(r.name()));
        }
        for o in self.ci.object_definitions() {
            let _ = writeln!(out, "class {};", class(o.name()));
        }
        for c in self.ci.callback_interface_definitions() {
            let _ = writeln!(out, "class {};", class(c.name()));
        }
        out.push('\n');
        out
    }

    /// `using Name = ...;` for each custom type, each after the custom types it uses.
    fn emit_custom_aliases(&self) -> String {
        let customs: Vec<(&str, &Type)> = self
            .ci
            .iter_local_types()
            .filter_map(|t| match t {
                Type::Custom { name, builtin, .. } => Some((name.as_str(), builtin.as_ref())),
                _ => None,
            })
            .collect();
        let mut out = String::new();
        let mut done = BTreeSet::new();
        for (name, _) in &customs {
            self.visit_custom(name, &customs, &mut done, &mut out);
        }
        out.push('\n');
        out
    }

    fn visit_custom<'t>(
        &self,
        name: &'t str,
        customs: &[(&'t str, &'t Type)],
        done: &mut BTreeSet<&'t str>,
        out: &mut String,
    ) {
        let Some((_, builtin)) = customs.iter().find(|(n, _)| *n == name) else {
            return;
        };
        if !done.insert(name) {
            return;
        }
        for inner in builtin.iter_types() {
            if let Type::Custom { name: dep, .. } = inner {
                self.visit_custom(dep, customs, done, out);
            }
        }
        let target = match self.custom_config(name).and_then(|c| c.type_name.clone()) {
            Some(type_name) => type_name,
            None => self.cpp_type(builtin),
        };
        let _ = writeln!(out, "using {} = {target};", class(name));
    }

    fn emit_flat_enum(&self, e: &Enum) -> String {
        let underlying = e
            .variant_discr_type()
            .as_ref()
            .map_or_else(|| "int32_t".to_owned(), |t| self.cpp_type(t));
        let mut out = doc(e.docstring(), 0);
        let _ = writeln!(out, "enum class {} : {underlying} {{", class(e.name()));
        for (i, v) in e.variants().iter().enumerate() {
            out.push_str(&doc(v.docstring(), 4));
            let discr = match e.variant_discr(i) {
                Ok(Literal::UInt(n, ..)) => n.to_string(),
                Ok(Literal::Int(n, ..)) => n.to_string(),
                _ => i.to_string(),
            };
            let _ = writeln!(out, "    {} = {discr},", class(v.name()));
        }
        let _ = writeln!(out, "}};\n");
        if let Some(v) = self.value_type(e.name()) {
            out.push_str(&self.flat_enum_function_declarations(&v));
        }
        out
    }

    fn emit_data_enum(&self, e: &Enum) -> String {
        let name = class(e.name());
        let value = self.value_type(e.name());
        let fieldwise_eq = value.as_ref().is_some_and(|v| v.traits.eq_eq.is_none());
        let mut out = doc(e.docstring(), 0);
        let _ = writeln!(out, "struct {name} {{");
        for v in e.variants() {
            out.push_str(&doc(v.docstring(), 4));
            let vname = member(v.name(), e.name());
            let _ = writeln!(out, "    struct {vname} {{");
            for (i, f) in v.fields().iter().enumerate() {
                out.push_str(&doc(f.docstring(), 8));
                let ty = f.as_type();
                let _ = writeln!(
                    out,
                    "        {} {}{};",
                    self.cpp_type(&ty),
                    member(&field(f.name(), i), &vname),
                    self.initializer(f.default_value(), &ty)
                );
            }
            if fieldwise_eq {
                let _ = writeln!(
                    out,
                    "        bool operator==(const {vname}& other) const;\n        bool operator!=(const {vname}& other) const {{ return !(*this == other); }}"
                );
            }
            let _ = writeln!(out, "    }};");
        }
        let alternatives: Vec<String> = e
            .variants()
            .iter()
            .map(|v| member(v.name(), e.name()))
            .collect();
        let _ = writeln!(
            out,
            "\n    using Variant = std::variant<{}>;",
            alternatives.join(", ")
        );
        let _ = writeln!(out, "    Variant variant;\n");
        // Not `= default`: a nested struct with default member initializers is not
        // default-constructible until this class is complete, which deletes it.
        let _ = writeln!(
            out,
            "    /// Holds the first variant.\n    {name}() : variant(std::in_place_index<0>) {{}}"
        );
        let _ = writeln!(
            out,
            "    template <class V, class = std::enable_if_t<\n            std::is_constructible_v<Variant, V&&> &&\n            !std::is_same_v<std::decay_t<V>, {name}>>>\n    {name}(V&& value) : variant(std::forward<V>(value)) {{}}\n"
        );
        let _ = writeln!(
            out,
            "    /// True if this value holds the variant `V`.\n    template <class V>\n    bool is() const {{ return std::holds_alternative<V>(variant); }}\n\n    /// The variant `V`, or null if this value holds another one.\n    template <class V>\n    const V* get_if() const {{ return std::get_if<V>(&variant); }}\n\n    /// Call `visitor` with the held variant.\n    template <class F>\n    decltype(auto) visit(F&& visitor) const {{ return std::visit(std::forward<F>(visitor), variant); }}"
        );
        if let Some(v) = &value {
            out.push_str(&self.value_member_declarations(v));
        }
        let _ = writeln!(out, "}};\n");
        out
    }

    fn emit_record(&self, r: &Record) -> String {
        let mut out = doc(r.docstring(), 0);
        let _ = writeln!(out, "struct {} {{", class(r.name()));
        for f in r.fields() {
            out.push_str(&doc(f.docstring(), 4));
            let ty = f.as_type();
            let _ = writeln!(
                out,
                "    {} {}{};",
                self.cpp_type(&ty),
                member(f.name(), r.name()),
                self.initializer(f.default_value(), &ty)
            );
        }
        if let Some(v) = self.value_type(r.name()) {
            out.push_str(&self.value_member_declarations(&v));
        }
        let _ = writeln!(out, "}};\n");
        out
    }

    fn emit_error_class(&self, e: &Enum) -> String {
        let name = class(e.name());
        let flat = e.is_flat();
        let members = self
            .value_type(e.name())
            .filter(|v| v.kind == ValueKind::Error)
            .map(|v| {
                let mut members = self.value_member_declarations(&v);
                if v.traits.display_fmt.is_some() {
                    members.push_str("    /// The Rust `Display` text.\n    const char* what() const noexcept override;\n\nprivate:\n    mutable std::string what_;\n");
                }
                members
            })
            .unwrap_or_default();
        let mut out = doc(e.docstring(), 0);
        let _ = writeln!(
            out,
            "class {name} : public uniffi::Exception {{\npublic:\n    ~{name}() override = default;\n    virtual int32_t uniffi_variant_index() const = 0;\n    virtual void uniffi_write_fields(uniffi::Writer& writer) const = 0;\n    /// Throws this error as its most derived type.\n    [[noreturn]] virtual void uniffi_throw() const = 0;\n{members}\nprotected:\n    explicit {name}(const std::string& what) : uniffi::Exception(what) {{}}\n}};\n"
        );
        for (i, v) in e.variants().iter().enumerate() {
            let vname = format!("{name}_{}", class(v.name()));
            out.push_str(&doc(v.docstring(), 0));
            let _ = writeln!(out, "class {vname} final : public {name} {{\npublic:");
            let (ctor_params, ctor_init, members) = if flat {
                (
                    "std::string message_".to_owned(),
                    format!("{name}(message_), message(std::move(message_))"),
                    "    std::string message;\n".to_owned(),
                )
            } else {
                let mut params = Vec::new();
                let mut inits = vec![format!("{name}(\"{name}::{}\")", v.name())];
                let mut members = String::new();
                for (j, f) in v.fields().iter().enumerate() {
                    let fname = member(&field(f.name(), j), &vname);
                    let ty = self.cpp_type(&f.as_type());
                    params.push(format!("{ty} {fname}_"));
                    inits.push(format!("{fname}(std::move({fname}_))"));
                    members.push_str(&format!("    {ty} {fname};\n"));
                }
                (params.join(", "), inits.join(", "), members)
            };
            if ctor_params.is_empty() {
                let _ = writeln!(out, "    {vname}() : {ctor_init} {{}}");
            } else if flat {
                let _ = writeln!(
                    out,
                    "    explicit {vname}({ctor_params}) : {ctor_init} {{}}"
                );
            } else {
                let _ = writeln!(out, "    {vname}({ctor_params}) : {ctor_init} {{}}");
            }
            out.push_str(&members);
            let _ = writeln!(
                out,
                "\n    int32_t uniffi_variant_index() const override {{ return {}; }}\n    void uniffi_write_fields(uniffi::Writer& writer) const override;\n    [[noreturn]] void uniffi_throw() const override {{ throw *this; }}\n}};\n",
                i + 1
            );
        }
        out
    }

    /// ` = default` for a field with a default value, else `{}` so that a
    /// default-constructed record is never left uninitialized.
    fn initializer(&self, default: Option<&DefaultValue>, ty: &Type) -> String {
        default
            .and_then(|d| self.default_value(d, ty))
            .map_or_else(|| "{}".to_owned(), |d| format!(" = {d}"))
    }

    /// `R name(args)` with default arguments (header) or without (source).
    pub(crate) fn signature(&self, c: &dyn Callable, name: &str, with_defaults: bool) -> String {
        let ret = self.return_type_of(c);
        format!("{ret} {name}({})", self.param_list(c, with_defaults))
    }

    pub(crate) fn return_type_of(&self, c: &dyn Callable) -> String {
        let ret = c
            .return_type()
            .map_or_else(|| "void".to_owned(), |t| self.cpp_type(t));
        if c.is_async() {
            format!("uniffi::Future<{ret}>")
        } else {
            ret
        }
    }

    pub(crate) fn param_list(&self, c: &dyn Callable, with_defaults: bool) -> String {
        let args = c.arguments();
        // C++ only allows defaults on the trailing parameters.
        let first_defaulted = args
            .iter()
            .rposition(|a| a.default_value().is_none())
            .map_or(0, |i| i + 1);
        args.iter()
            .enumerate()
            .map(|(i, a)| {
                let ty = a.as_type();
                let mut s = format!("{} {}", self.param_type(&ty), var(a.name()));
                if with_defaults
                    && i >= first_defaulted
                    && let Some(d) = a.default_value().and_then(|d| self.default_value(d, &ty))
                {
                    s.push_str(&format!(" = {d}"));
                }
                s
            })
            .collect::<Vec<_>>()
            .join(", ")
    }

    fn emit_callback_interface_class(&self, cb: &CallbackInterface) -> String {
        let name = class(cb.name());
        let mut out = doc(cb.docstring(), 0);
        let _ = writeln!(
            out,
            "class {name} {{\npublic:\n    virtual ~{name}() = default;"
        );
        for m in cb.methods() {
            out.push_str(&doc(m.docstring(), 4));
            let _ = writeln!(
                out,
                "    virtual {} = 0;",
                self.signature(m, &member(m.name(), cb.name()), false)
            );
        }
        let _ = writeln!(out, "}};\n");
        out
    }

    fn emit_object_class(&self, obj: &Object) -> String {
        let name = class(obj.name());
        let mut out = doc(obj.docstring(), 0);
        let abstract_class = obj.is_trait_interface() || obj.has_callback_interface();
        let traits = obj.uniffi_trait_methods();
        if abstract_class && self.is_error_object(obj.name()) {
            // A trait used as an error: implementations are exceptions.
            let _ = writeln!(
                out,
                "class {name} : public uniffi::Exception {{\nprotected:\n    {name}() : uniffi::Exception(\"{name}\") {{}}\n    {name}(const {name}&) = default;\n\npublic:\n    ~{name}() override = default;"
            );
            for m in obj.methods() {
                out.push_str(&doc(m.docstring(), 4));
                let _ = writeln!(
                    out,
                    "    virtual {} = 0;",
                    self.signature(m, &member(m.name(), obj.name()), false)
                );
            }
        } else if abstract_class {
            let _ = writeln!(
                out,
                "class {name} {{\npublic:\n    virtual ~{name}() = default;"
            );
            for m in obj.methods() {
                out.push_str(&doc(m.docstring(), 4));
                let _ = writeln!(
                    out,
                    "    virtual {} = 0;",
                    self.signature(m, &member(m.name(), obj.name()), false)
                );
            }
        } else if self.is_error_object(obj.name()) {
            // Thrown as an exception, so it must be copyable: a copy is a new reference.
            let what = if traits.display_fmt.is_some() {
                "\n    /// The Rust `Display` text.\n    const char* what() const noexcept override;\n"
            } else {
                ""
            };
            let _ = writeln!(
                out,
                "class {name} : public uniffi::Exception {{\npublic:\n    /// Wraps a handle owned by Rust. Not meant to be called directly.\n    {name}(uniffi::HandleTag, uint64_t handle) : uniffi::Exception(\"{name}\"), handle_(handle) {{}}\n    ~{name}() override;\n    {name}(const {name}& other) : uniffi::Exception(other), handle_(other.uniffi_clone_handle()) {{}}\n    {name}& operator=(const {name}&) = delete;\n{what}"
            );
            out.push_str(&self.object_members(obj));
        } else {
            let _ = writeln!(out, "class {name} {{\npublic:");
            let _ = writeln!(
                out,
                "    /// Wraps a handle owned by Rust. Not meant to be called directly.\n    {name}(uniffi::HandleTag, uint64_t handle) : handle_(handle) {{}}\n    ~{name}();\n    {name}(const {name}&) = delete;\n    {name}& operator=(const {name}&) = delete;\n"
            );
            out.push_str(&self.object_members(obj));
        }
        if !abstract_class {
            out.push_str(&trait_declarations(&name, &traits));
        }
        if !abstract_class {
            let what_cache = if self.is_error_object(obj.name()) && traits.display_fmt.is_some() {
                "\n    mutable std::string what_;"
            } else {
                ""
            };
            let _ = writeln!(out, "\nprivate:\n    uint64_t handle_;{what_cache}");
        }
        let _ = writeln!(out, "}};\n");
        out
    }

    /// Constructors, methods and `uniffi_clone_handle` of a Rust-backed object.
    fn object_members(&self, obj: &Object) -> String {
        let mut out = String::new();
        for c in obj.constructors() {
            out.push_str(&doc(c.docstring(), 4));
            let _ = writeln!(
                out,
                "    static {};",
                self.signature(c, &member(c.name(), obj.name()), true)
            );
        }
        for m in obj.methods() {
            out.push_str(&doc(m.docstring(), 4));
            let _ = writeln!(
                out,
                "    {} const;",
                self.signature(m, &member(m.name(), obj.name()), true)
            );
        }
        let _ = writeln!(
            out,
            "\n    /// A new reference to the Rust object, for passing to Rust.\n    uint64_t uniffi_clone_handle() const;"
        );
        out
    }

    fn emit_detail_declarations(&self) -> String {
        let mut out = String::from(
            "/// Plumbing shared with other components that use this one's types.\nnamespace uniffi_detail {\n/// Checks the library and registers the callback interfaces, once.\nvoid ensure_init();\n",
        );
        for o in self.ci.object_definitions() {
            let name = class(o.name());
            let _ = writeln!(
                out,
                "std::shared_ptr<{name}> lift_{name}(uint64_t handle);\nuint64_t lower_{name}(const std::shared_ptr<{name}>& value);"
            );
        }
        for c in self.ci.callback_interface_definitions() {
            let name = class(c.name());
            let _ = writeln!(
                out,
                "std::shared_ptr<{name}> lift_{name}(uint64_t handle);\nuint64_t lower_{name}(const std::shared_ptr<{name}>& value);"
            );
        }
        let errors = self
            .ci
            .enum_definitions()
            .iter()
            .map(|e| e.name())
            .filter(|n| self.is_error_enum(n))
            .chain(
                self.ci
                    .object_definitions()
                    .iter()
                    .map(|o| o.name())
                    .filter(|n| self.is_error_object(n)),
            );
        for name in errors {
            let _ = writeln!(
                out,
                "[[noreturn]] void throw_buf_{}(uniffi::RustBuffer buffer);",
                class(name)
            );
        }
        let _ = writeln!(out, "}}  // namespace uniffi_detail\n");
        out
    }

    /// `uniffi::Codec` specializations for every type defined by this component.
    ///
    /// All codecs are declared before any is defined, and value codecs are defined out of
    /// line after that, so that types can refer to each other in any order (`Value` holds
    /// `std::vector<Entry>` and `Entry` holds a `Value`).
    fn emit_codecs(&self) -> String {
        let mut out = String::from("namespace uniffi {\n\n");
        let value_defs = self.ordered_value_defs();
        for def in &value_defs {
            let _ = writeln!(
                out,
                "template <>\nstruct Codec<{}>;",
                self.codec_type(def.name())
            );
        }
        for name in self.handle_type_names() {
            let _ = writeln!(
                out,
                "template <>\nstruct Codec<std::shared_ptr<{}>>;",
                self.local(name)
            );
        }
        out.push('\n');
        for name in self.handle_type_names() {
            out.push_str(&self.codec_handle(name));
        }
        let mut definitions = String::new();
        for def in &value_defs {
            let codec = match def {
                ValueDef::Record(r) => self.codec_record(r),
                ValueDef::Enum(e) if self.is_error_enum(e.name()) => self.codec_error(e),
                ValueDef::Enum(e) if e.is_flat() => self.codec_flat_enum(e),
                ValueDef::Enum(e) => self.codec_data_enum(e),
            };
            out.push_str(&codec.declaration);
            definitions.push_str(&codec.definition);
        }
        out.push_str(&self.codec_custom());
        out.push_str(&definitions);
        let _ = writeln!(out, "}}  // namespace uniffi\n");
        out.push_str(&self.emit_error_field_writers());
        out
    }

    /// Objects and callback interfaces: the types passed as handles.
    fn handle_type_names(&self) -> Vec<&str> {
        self.ci
            .object_definitions()
            .iter()
            .map(|o| o.name())
            .chain(
                self.ci
                    .callback_interface_definitions()
                    .iter()
                    .map(|c| c.name()),
            )
            .collect()
    }

    /// The type a value codec is specialized for: errors travel as `std::shared_ptr`.
    fn codec_type(&self, name: &str) -> String {
        let full = self.local(name);
        if self.is_error_enum(name) {
            format!("std::shared_ptr<{full}>")
        } else {
            full
        }
    }

    /// A codec whose `read` and `write` are defined after all codecs are declared.
    fn value_codec(&self, full: &str, write_param: &str, read: &str, write: &str) -> Codec {
        Codec {
            declaration: format!(
                "template <>\nstruct Codec<{full}> {{\n    static {full} read(Reader& reader);\n    static void write(Writer& writer, {write_param} value);\n}};\n\n"
            ),
            definition: format!(
                "inline {full} Codec<{full}>::read(Reader& reader) {{\n    (void)reader;\n{read}}}\n\ninline void Codec<{full}>::write(Writer& writer, {write_param} value) {{\n    (void)writer;\n    (void)value;\n{write}}}\n\n"
            ),
        }
    }

    fn codec_record(&self, r: &Record) -> Codec {
        let full = self.local(r.name());
        let mut read = String::new();
        let mut args = Vec::new();
        let mut write = String::new();
        for (i, f) in r.fields().iter().enumerate() {
            let ty = self.cpp_type(&f.as_type());
            read.push_str(&format!("    auto f{i} = Codec<{ty}>::read(reader);\n"));
            args.push(format!("std::move(f{i})"));
            write.push_str(&format!(
                "    Codec<{ty}>::write(writer, value.{});\n",
                member(f.name(), r.name())
            ));
        }
        read.push_str(&format!("    return {full}{{{}}};\n", args.join(", ")));
        self.value_codec(&full, &format!("const {full}&"), &read, &write)
    }

    fn codec_flat_enum(&self, e: &Enum) -> Codec {
        let full = self.local(e.name());
        let mut read = String::from("    switch (reader.read_int<int32_t>()) {\n");
        let mut write = String::from("    switch (value) {\n");
        for (i, v) in e.variants().iter().enumerate() {
            let variant = format!("{full}::{}", class(v.name()));
            read.push_str(&format!("        case {}: return {variant};\n", i + 1));
            write.push_str(&format!(
                "        case {variant}: writer.write_int<int32_t>({});\n            return;\n",
                i + 1
            ));
        }
        read.push_str("        default: throw InternalError(\"unexpected enum case\");\n    }\n");
        write.push_str("    }\n    throw InternalError(\"unexpected enum value\");\n");
        self.value_codec(&full, &full, &read, &write)
    }

    fn codec_data_enum(&self, e: &Enum) -> Codec {
        let full = self.local(e.name());
        let mut read = String::from("    switch (reader.read_int<int32_t>()) {\n");
        let mut write = String::from("    switch (value.variant.index()) {\n");
        for (i, v) in e.variants().iter().enumerate() {
            let vname = member(v.name(), e.name());
            let vfull = format!("{full}::{vname}");
            let mut body = String::new();
            let mut args = Vec::new();
            let mut writes = String::new();
            for (j, f) in v.fields().iter().enumerate() {
                let ty = self.cpp_type(&f.as_type());
                body.push_str(&format!(
                    "            auto f{j} = Codec<{ty}>::read(reader);\n"
                ));
                args.push(format!("std::move(f{j})"));
                writes.push_str(&format!(
                    "            Codec<{ty}>::write(writer, variant.{});\n",
                    member(&field(f.name(), j), &vname)
                ));
            }
            read.push_str(&format!(
                "        case {}: {{\n{body}            return {full}({vfull}{{{}}});\n        }}\n",
                i + 1,
                args.join(", ")
            ));
            write.push_str(&format!(
                "        case {i}: {{\n            const auto& variant = std::get<{i}>(value.variant);\n            (void)variant;\n            writer.write_int<int32_t>({});\n{writes}            return;\n        }}\n",
                i + 1
            ));
        }
        read.push_str("        default: throw InternalError(\"unexpected enum case\");\n    }\n");
        write.push_str("    }\n    throw InternalError(\"unexpected enum value\");\n");
        self.value_codec(&full, &format!("const {full}&"), &read, &write)
    }

    /// Errors travel as `std::shared_ptr` to the base class, to keep the variant.
    fn codec_error(&self, e: &Enum) -> Codec {
        let base = self.local(e.name());
        let full = format!("std::shared_ptr<{base}>");
        let name = class(e.name());
        let mut read = String::from("    switch (reader.read_int<int32_t>()) {\n");
        for (i, v) in e.variants().iter().enumerate() {
            let vfull = format!("::{}::{name}_{}", self.ns, class(v.name()));
            if e.is_flat() {
                read.push_str(&format!(
                    "        case {}: return std::make_shared<{vfull}>(Codec<std::string>::read(reader));\n",
                    i + 1
                ));
            } else {
                let mut body = String::new();
                let mut args = Vec::new();
                for (j, f) in v.fields().iter().enumerate() {
                    let ty = self.cpp_type(&f.as_type());
                    body.push_str(&format!(
                        "            auto f{j} = Codec<{ty}>::read(reader);\n"
                    ));
                    args.push(format!("std::move(f{j})"));
                }
                read.push_str(&format!(
                    "        case {}: {{\n{body}            return std::make_shared<{vfull}>({});\n        }}\n",
                    i + 1,
                    args.join(", ")
                ));
            }
        }
        read.push_str(
            "        default: throw InternalError(\"unexpected error variant\");\n    }\n",
        );
        Codec {
            declaration: format!(
                "template <>\nstruct Codec<{full}> {{\n    static {full} read(Reader& reader);\n    static void write(Writer& writer, const {full}& value);\n    static void write_value(Writer& writer, const {base}& value) {{\n        writer.write_int<int32_t>(value.uniffi_variant_index());\n        value.uniffi_write_fields(writer);\n    }}\n}};\n\n"
            ),
            definition: format!(
                "inline {full} Codec<{full}>::read(Reader& reader) {{\n{read}}}\n\ninline void Codec<{full}>::write(Writer& writer, const {full}& value) {{\n    if (!value) {{\n        throw InternalError(\"a null error cannot be passed to Rust\");\n    }}\n    write_value(writer, *value);\n}}\n\n"
            ),
        }
    }

    /// `uniffi_write_fields` of error variants, defined once the codecs of their fields are.
    fn emit_error_field_writers(&self) -> String {
        let mut out = String::new();
        for e in self.ci.enum_definitions() {
            if !self.is_error_enum(e.name()) {
                continue;
            }
            let name = class(e.name());
            for v in e.variants() {
                let vname = format!("{name}_{}", class(v.name()));
                let mut writes = String::new();
                if !e.is_flat() {
                    for (j, f) in v.fields().iter().enumerate() {
                        let _ = writeln!(
                            writes,
                            "    uniffi::Codec<{}>::write(writer, {});",
                            self.cpp_type(&f.as_type()),
                            member(&field(f.name(), j), &vname)
                        );
                    }
                }
                let _ = writeln!(
                    out,
                    "inline void {}::{vname}::uniffi_write_fields(uniffi::Writer& writer) const {{\n    (void)writer;\n{writes}}}\n",
                    self.ns
                );
            }
        }
        out
    }

    fn codec_handle(&self, name: &str) -> String {
        let full = self.local(name);
        let n = class(name);
        let ns = &self.ns;
        format!(
            "template <>\nstruct Codec<std::shared_ptr<{full}>> {{\n    static std::shared_ptr<{full}> read(Reader& reader) {{\n        return {ns}::uniffi_detail::lift_{n}(reader.read_int<uint64_t>());\n    }}\n    static void write(Writer& writer, const std::shared_ptr<{full}>& value) {{\n        writer.write_int<uint64_t>({ns}::uniffi_detail::lower_{n}(value));\n    }}\n}};\n\n"
        )
    }

    /// Codecs for custom types that map to a C++ type of the user's choosing.
    fn codec_custom(&self) -> String {
        let mut out = String::new();
        let mut seen = BTreeSet::new();
        for t in self.ci.iter_local_types() {
            let Type::Custom { name, builtin, .. } = t else {
                continue;
            };
            let Some(cfg) = self.custom_config(name) else {
                continue;
            };
            let Some(type_name) = &cfg.type_name else {
                continue;
            };
            let builtin_cpp = self.cpp_type(builtin);
            if *type_name == builtin_cpp || !seen.insert(type_name.clone()) {
                continue;
            }
            let lifted = cfg.lift(&format!("Codec<{builtin_cpp}>::read(reader)"));
            let lowered = cfg.lower("value");
            let _ = writeln!(
                out,
                "template <>\nstruct Codec<{type_name}> {{\n    static {type_name} read(Reader& reader) {{ return {lifted}; }}\n    static void write(Writer& writer, const {type_name}& value) {{ Codec<{builtin_cpp}>::write(writer, {lowered}); }}\n}};\n"
            );
        }
        out
    }
}
